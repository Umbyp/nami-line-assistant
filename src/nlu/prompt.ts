import { inZone, THAI_DOW_FULL } from '../lib/time.js';
import { env } from '../config/env.js';

const THAI_MONTHS_FULL = [
  'มกราคม', 'กุมภาพันธ์', 'มีนาคม', 'เมษายน', 'พฤษภาคม', 'มิถุนายน',
  'กรกฎาคม', 'สิงหาคม', 'กันยายน', 'ตุลาคม', 'พฤศจิกายน', 'ธันวาคม',
];

export interface PromptContext {
  now: Date;
  tz: string;
  isGroup: boolean;
  /** ชื่อสมาชิกในกลุ่มที่เรารู้จักแล้ว ใช้ช่วยโมเดลจับชื่อคนที่ถูกมอบหมาย */
  knownMemberNames?: string[];
}

/**
 * ประโยคบอก "เดี๋ยวนี้" ให้โมเดล — ต้องละเอียดถึงระดับวันในสัปดาห์
 * เพราะคำอย่าง "วันศุกร์หน้า" คำนวณไม่ได้ถ้าไม่รู้ว่าวันนี้วันอะไร
 */
export function describeNow(now: Date, tz: string = env.APP_TIMEZONE): string {
  const l = inZone(now, tz);
  const dow = THAI_DOW_FULL[l.weekday - 1] ?? '';
  const mon = THAI_MONTHS_FULL[l.month - 1] ?? '';
  return (
    `ขณะนี้คือวัน${dow}ที่ ${l.day} ${mon} ${l.year} (พ.ศ. ${l.year + 543}) ` +
    `เวลา ${l.toFormat('HH:mm')} ตามเวลาไทย (${tz})`
  );
}

/**
 * กฎการอ่านเวลาแบบไทย — ส่วนที่โมเดลพลาดบ่อยที่สุดถ้าไม่บอก
 * เขียนเป็นตารางเทียบตรงๆ ไม่อธิบายเป็นความเรียง เพื่อให้โมเดลจับได้แน่น
 */
const THAI_TIME_RULES = `
วิธีอ่านเวลาแบบไทย (สำคัญมาก):
- "18.00" "18:00" "18 นาฬิกา" = 18:00   (ไทยใช้จุดคั่นชั่วโมงกับนาที ไม่ใช่ทศนิยม)
- "ตี 1" ถึง "ตี 5" = 01:00-05:00
- "6 โมงเช้า" = 06:00 · "7 โมง" / "โมงเช้า" = 07:00 · "8 โมงเช้า" = 08:00
- "เที่ยง" "เที่ยงวัน" = 12:00 · "เที่ยงคืน" = 00:00
- "บ่ายโมง" = 13:00 · "บ่าย 2" = 14:00 · "บ่าย 3" = 15:00 (บ่าย N = 12+N)
- "4 โมงเย็น" = 16:00 · "5 โมงเย็น" = 17:00 · "6 โมงเย็น" = 18:00 (N โมงเย็น = 12+N)
- "1 ทุ่ม" = 19:00 · "2 ทุ่ม" = 20:00 · "3 ทุ่ม" = 21:00 (N ทุ่ม = 18+N)
- "ครึ่ง" = นาทีที่ 30 เช่น "บ่าย 2 ครึ่ง" = 14:30 · "5 โมงครึ่ง" = 17:30

คำที่ถือว่า "กำกวม" ต้องใส่ ambiguousFields = ["time"] และห้ามเดาเวลาให้:
  "เย็นๆ" "ตอนเย็น" "ตอนบ่าย" "ตอนเช้า" "ดึกๆ" "เร็วๆ นี้" "เดี๋ยว" "สายๆ"
แต่ถ้าคำเหล่านั้นมาพร้อมเวลาชัดเจน ให้ใช้เวลานั้นและไม่ต้องถาม
  เช่น "เตือนกินยาหลังอาหารเย็น 18.00" → 18:00 และ title = "กินยาหลังอาหารเย็น"

วันแบบสัมพัทธ์:
- "พรุ่งนี้" = +1 วัน · "มะรืนนี้" = +2 วัน · "เมื่อวาน" = -1 วัน
- "วันจันทร์หน้า" = วันจันทร์ของสัปดาห์ถัดไป (ไม่ใช่วันจันทร์ที่ใกล้ที่สุด)
- "วันศุกร์นี้" = วันศุกร์ของสัปดาห์นี้ ถ้าผ่านไปแล้วให้เป็นสัปดาห์หน้า
- "อีก 2 ชั่วโมง" "อีก 30 นาที" = บวกจากเวลาปัจจุบัน
- ปีในเอกสาร/ข้อความไทยมักเป็น พ.ศ. ต้องแปลงเป็น ค.ศ. เสมอ (ค.ศ. = พ.ศ. - 543)
`.trim();

const RECURRENCE_RULES = `
การเตือนซ้ำ (kind = "recurring"):
- "ทุกวัน" → FREQ=DAILY
- "ทุกวันจันทร์" → FREQ=WEEKLY;BYDAY=MO
- "ทุกวันจันทร์-ศุกร์" "ทุกวันทำงาน" → FREQ=WEEKLY;BYDAY=MO,TU,WE,TH,FR
- "ทุกวันเสาร์อาทิตย์" → FREQ=WEEKLY;BYDAY=SA,SU
- "ทุกวันที่ 25" → FREQ=MONTHLY;BYMONTHDAY=25
- "ทุกเดือน" → FREQ=MONTHLY
- "ทุกปี" หรือวันเกิด/วันครบรอบ → FREQ=YEARLY;BYMONTH=<เดือน>;BYMONTHDAY=<วัน>
- "ทุก 30 นาที" "ทุก 2 ชั่วโมง" → ใช้ everyMinutes (30 / 120) และ rrule = null
รหัสวัน: MO TU WE TH FR SA SU

สำคัญมาก — "ซ้ำ" ต้องมีตัวบอกความซ้ำชัดเจนเท่านั้น:
- "ทุกวันจันทร์ 5 โมงเย็น"  → recurring (มีคำว่า "ทุก")
- "วันจันทร์ 5 โมงเย็น"     → once ไม่ใช่ recurring! หมายถึงวันจันทร์ที่จะถึงครั้งเดียว
- "วันศุกร์ 2 ทุ่ม"          → once
ถ้าไม่มีคำว่า ทุก / ประจำ / ซ้ำ หรือช่วงวันแบบ "จันทร์-ศุกร์" ให้ถือว่าเป็น once เสมอ

ถ้าเป็น recurring แต่ผู้ใช้ไม่บอกเวลาที่จะเตือน ให้ใส่ ambiguousFields = ["time"]
ห้ามเดาเวลาเอง
`.trim();

export function buildSystemPrompt(ctx: PromptContext): string {
  const parts: string[] = [
    'คุณคือตัวแยกความหมาย (NLU) ของ "นามิ" ผู้ช่วยส่วนตัวในแชท LINE',
    'หน้าที่ของคุณคือแปลงข้อความภาษาไทยของผู้ใช้เป็นข้อมูลตาม schema เท่านั้น',
    'คุณไม่ได้คุยกับผู้ใช้ ไม่ต้องทักทาย ไม่ต้องอธิบาย ตอบเป็น JSON ตาม schema อย่างเดียว',
    '',
    describeNow(ctx.now, ctx.tz),
    '',
    THAI_TIME_RULES,
    '',
    RECURRENCE_RULES,
    '',
    [
      'การเลือก intent:',
      '- create_reminder = ผู้ใช้อยากให้เตือน ("เตือน...", "อย่าลืม...", "นัด...")',
      '- list_reminders  = อยากดูรายการเตือนที่มีอยู่',
      '- cancel_reminder = อยากยกเลิก/ลบการเตือน',
      '- search_vault    = อยากค้นของที่เคยส่งไว้ ("หาไฟล์...", "ลิงก์ที่...ส่ง")',
      '- save_to_vault   = อยากให้เก็บข้อความ/ลิงก์นี้ไว้ ("เก็บไว้ให้ด้วย", "จำไว้นะ")',
      '- help            = ถามว่าใช้งานยังไง ทำอะไรได้',
      '- smalltalk       = ทักทาย ขอบคุณ คุยเล่น',
      '- unknown         = อ่านไม่ออกว่าต้องการอะไร',
    ].join('\n'),
    '',
    [
      'กฎเหล็ก 3 ข้อ:',
      '1. ห้ามเดาข้อมูลที่ผู้ใช้ไม่ได้บอก ถ้าเดาไม่ได้ให้ใส่ใน ambiguousFields แล้วตั้ง clarifyQuestion',
      '2. title ต้องเป็นเรื่องที่จะเตือน ห้ามมีวลีบอกเวลาปนอยู่',
      '3. เวลาทั้งหมดเป็นเวลาไทย ปีเป็น ค.ศ. เสมอ',
    ].join('\n'),
  ];

  if (ctx.isGroup) {
    parts.push(
      '',
      'ข้อความนี้มาจากแชทกลุ่ม ผู้ใช้อาจมอบหมายงานให้คนอื่น',
      'ให้เก็บชื่อคนที่ถูกมอบหมายไว้ใน assigneeNames ตามที่พิมพ์มา',
    );
    if (ctx.knownMemberNames?.length) {
      parts.push(
        `สมาชิกในกลุ่มที่รู้จักแล้ว: ${ctx.knownMemberNames.join(', ')}`,
        'ถ้าชื่อที่ผู้ใช้พิมพ์ตรงกับคนในลิสต์นี้ ให้ใช้ชื่อในลิสต์',
      );
    }
  }

  return parts.join('\n');
}
