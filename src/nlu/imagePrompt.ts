import { describeNow } from './prompt.js';
import { env } from '../config/env.js';

/**
 * prompt สำหรับอ่านรูป (ใบนัดหมอ/ตารางเรียน/ตารางเวร/สลิป) แล้วดึงเป็นรายการเตือน
 *
 * กฎสำคัญที่ต่างจาก NLU ข้อความ (buildSystemPrompt):
 *   - ไม่ให้โมเดลคำนวณ "นาทีจากเที่ยงคืน" เป็นตัวเลขเอง (ประวัติพลาดซ้ำๆ ดู thaiTime.ts)
 *     ให้คัดลอกเวลาที่เห็นมาเป็นข้อความ (timeText) แล้วโค้ดฝั่งเราคำนวณเองด้วย extractClockMinute
 *   - เอกสารมักมีหลายรายการ (เช่นตารางเวรทั้งสัปดาห์) ต้องแยกเป็นหลาย reminder ไม่ใช่รวมเป็นอันเดียว
 *   - ปีในเอกสารไทยมักเป็น พ.ศ. ต้องแปลงเป็น ค.ศ. เสมอ
 */
export function buildImagePrompt(now: Date, tz: string = env.APP_TIMEZONE): string {
  return [
    'คุณคือตัวอ่านเอกสารภาพของ "นามิ" ผู้ช่วยส่วนตัวในแชท LINE',
    'หน้าที่: อ่านรูปที่แนบมา (ใบนัดหมอ/ตารางเรียน/ตารางเวร/สลิป ฯลฯ) แล้วดึงรายการที่ควรตั้งเตือน',
    'ไม่ได้คุยกับผู้ใช้ ไม่ต้องอธิบาย ตอบเป็น JSON ตาม schema อย่างเดียว',
    '',
    describeNow(now, tz),
    '',
    [
      'กฎเหล็ก:',
      '1. ปีในเอกสารไทยมักเป็น พ.ศ. ต้องแปลงเป็น ค.ศ. เสมอ (ค.ศ. = พ.ศ. - 543)',
      '2. ห้ามคำนวณเวลาเป็นนาทีเอง — ให้คัดลอกเวลาที่เห็นในเอกสารมาเป็นข้อความใน timeText ' +
        'ตรงตามต้นฉบับที่สุด เช่น "09:30" "8 โมงเช้า" "13.00 น."',
      '3. เอกสารที่มีหลายรายการ (ตารางเวรทั้งสัปดาห์, หลายนัด) ต้องแยกเป็นหลาย reminder',
      '4. ตารางเรียน/ตารางเวรที่ซ้ำทุกสัปดาห์ (มีคำว่าเป็นตารางประจำ ไม่ใช่วันที่เฉพาะ) → kind=recurring',
      '   ใบนัด/ใบเสร็จที่มีวันที่ชัดเจนวันเดียว → kind=once',
      '5. อะไรอ่านไม่ชัดหรือไม่มั่นใจ (ตัวเลขเลือน, ลายมือ) ต้องใส่ใน unclearNotes ห้ามเดาแล้วไม่บอก',
      '6. title ต้องเป็นเรื่องที่จะเตือน ห้ามมีวันเวลาปนอยู่ในชื่อ',
      '7. ไม่ใช่เอกสารที่มีอะไรให้เตือนเลย (เช่นรูปถ่ายทั่วไป) ให้ reminders เป็น array ว่าง docType=other',
    ].join('\n'),
  ].join('\n');
}
